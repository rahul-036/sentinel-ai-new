"""
SOSService — alert generation, guardian notification, and in-memory storage.

Version 1 design
----------------
  create_sos_alert()    — original function, unchanged (backward-compatible).
  create_sos_alert_v2() — extended version that attaches guardian notifications.
  notify_guardians()    — dispatches simulated notifications to all guardians.
  get_all_alerts()      — returns full alert history.
  get_alert_by_id()     — single-alert lookup.

Upgrading to real notifications (Version 2):
  Replace SimulatedDispatcher with TwilioSMSDispatcher in notification_service.py.
  Zero changes required here.
"""

import threading
from datetime import datetime, timezone

import structlog

from app.schemas.sos import SOSAlert, SOSRequest
from app.services.guardian_service import get_all_guardians
from app.services.notification_service import get_dispatcher

logger = structlog.get_logger(__name__)

# ---------------------------------------------------------------------------
# In-memory store (thread-safe)
# ---------------------------------------------------------------------------

_alerts: list[SOSAlert] = []
_store_lock = threading.Lock()
_daily_counter: dict[str, int] = {}
_counter_lock = threading.Lock()


# ---------------------------------------------------------------------------
# Alert ID generator
# ---------------------------------------------------------------------------

def _next_alert_id(date_str: str) -> str:
    """Return the next sequential ID for today, e.g. SOS-20260730-0001."""
    with _counter_lock:
        seq = _daily_counter.get(date_str, 0) + 1
        _daily_counter[date_str] = seq
    return f"SOS-{date_str}-{seq:04d}"


# ---------------------------------------------------------------------------
# Emergency message builder
# ---------------------------------------------------------------------------

def _build_message(req: SOSRequest, timestamp: datetime) -> str:
    return (
        f"Emergency SOS generated by {req.user_name}.\n"
        f"Current Risk Level: {req.risk_level}\n"
        f"Safety Score: {req.safety_score}\n"
        f"Location: {req.latitude},{req.longitude}\n"
        f"Time: {timestamp.strftime('%Y-%m-%dT%H:%M:%S')} UTC"
    )


# ---------------------------------------------------------------------------
# Guardian notification
# ---------------------------------------------------------------------------

async def notify_guardians(
    alert_id: str,
    req: SOSRequest,
    timestamp: datetime,
) -> list[dict]:
    """
    Dispatch a notification to every registered guardian.

    Returns a list of dicts compatible with NotifiedGuardian schema.
    Never raises — individual failures are captured per-guardian.
    """
    guardians = get_all_guardians()
    dispatcher = get_dispatcher()
    results: list[dict] = []

    for guardian in guardians:
        try:
            status = await dispatcher.dispatch(
                alert_id=alert_id,
                user_name=req.user_name,
                risk_level=req.risk_level,
                safety_score=req.safety_score,
                latitude=req.latitude,
                longitude=req.longitude,
                guardian_name=guardian.name,
                guardian_phone=guardian.phone,
                guardian_email=guardian.email,
            )
        except Exception as exc:  # noqa: BLE001
            logger.error(
                "Guardian notification failed",
                guardian_id=guardian.id,
                guardian=guardian.name,
                error=str(exc),
            )
            status = "failed"

        results.append({
            "id": guardian.id,
            "name": guardian.name,
            "phone": guardian.phone,
            "relation": guardian.relation,
            "notification_status": status,
        })

    logger.info(
        "Guardian notifications complete",
        alert_id=alert_id,
        total=len(results),
        simulated=sum(1 for r in results if r["notification_status"] == "simulated"),
        failed=sum(1 for r in results if r["notification_status"] == "failed"),
    )
    return results


# ---------------------------------------------------------------------------
# Original public function — UNCHANGED (backward-compatible)
# ---------------------------------------------------------------------------

def create_sos_alert(req: SOSRequest) -> SOSAlert:
    """
    Validate, generate, store, and return a new SOSAlert.
    Kept identical to the original for backward compatibility.
    """
    try:
        now = datetime.now(tz=timezone.utc)
        date_str = now.strftime("%Y%m%d")
        alert_id = _next_alert_id(date_str)
        message = _build_message(req, now)

        alert = SOSAlert(
            alert_id=alert_id,
            user_name=req.user_name,
            phone=req.phone,
            latitude=req.latitude,
            longitude=req.longitude,
            safety_score=req.safety_score,
            risk_level=req.risk_level,
            timestamp=now,
            emergency_message=message,
        )

        with _store_lock:
            _alerts.append(alert)

        logger.info(
            "SOS alert stored",
            alert_id=alert_id,
            user=req.user_name,
            risk_level=req.risk_level,
            safety_score=req.safety_score,
            latitude=req.latitude,
            longitude=req.longitude,
            timestamp=now.isoformat(),
        )
        return alert

    except Exception as exc:
        logger.error("SOSService failed to create alert", error=str(exc))
        raise RuntimeError(f"SOS service error: {exc}") from exc


# ---------------------------------------------------------------------------
# Extended public function — used by the new SOSAgent
# ---------------------------------------------------------------------------

async def create_sos_alert_v2(req: SOSRequest) -> SOSAlert:
    """
    Create an alert AND notify all registered guardians.

    Stores guardian notification results on the alert record so
    /sos/history can return them.
    """
    try:
        now = datetime.now(tz=timezone.utc)
        date_str = now.strftime("%Y%m%d")
        alert_id = _next_alert_id(date_str)
        message = _build_message(req, now)

        # Notify guardians before storing so the alert record is complete
        guardian_results = await notify_guardians(alert_id, req, now)

        alert = SOSAlert(
            alert_id=alert_id,
            user_name=req.user_name,
            phone=req.phone,
            latitude=req.latitude,
            longitude=req.longitude,
            safety_score=req.safety_score,
            risk_level=req.risk_level,
            timestamp=now,
            emergency_message=message,
            guardians_notified=guardian_results,
        )

        with _store_lock:
            _alerts.append(alert)

        logger.info(
            "SOS alert v2 stored",
            alert_id=alert_id,
            user=req.user_name,
            risk_level=req.risk_level,
            guardian_count=len(guardian_results),
        )
        return alert

    except Exception as exc:
        logger.error("SOSService v2 failed", error=str(exc))
        raise RuntimeError(f"SOS service error: {exc}") from exc


# ---------------------------------------------------------------------------
# Read helpers
# ---------------------------------------------------------------------------

def get_all_alerts() -> list[SOSAlert]:
    with _store_lock:
        return list(reversed(_alerts))   # newest first


def get_alert_by_id(alert_id: str) -> SOSAlert | None:
    with _store_lock:
        return next((a for a in _alerts if a.alert_id == alert_id), None)
